#!/usr/bin/env python3
"""Regenerate the Onyx score-name overlay (FORK-ONLY).

Writes app/src/release/res/values/strings.xml: every English string that names NOOP's scores, re-worded
with WHOOP's names — Charge -> Recovery, Effort -> Strain, Rest -> Sleep. A build-type resource set
OVERRIDES main, so upstream's strings.xml is never edited and merges stay clean. Re-run after every
upstream merge; strings upstream added since last time are picked up, removed ones simply drop out.

Usage:  python3 android/onyx/gen_score_names.py
"""

from __future__ import annotations

import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SRC = HERE.parent / "app/src/main/res/values/strings.xml"
OUT = HERE.parent / "app/src/release/res/values/strings.xml"

# Only CAPITALISED whole words are score names. Lower-case "effort" is ordinary English ("best-effort",
# "your effort zone") and lower-case "charge" is the battery.
SWAPS = [(re.compile(r"\bCharge\b"), "Recovery"), (re.compile(r"\bEffort\b"), "Strain"), (re.compile(r"\bRest\b"), "Sleep")]

# Capitalised but NOT the score: the battery, the interval timer's rest period, resting heart rate.
SKIP = {
    "battery_critical_title",              # "Charge your WHOOP now"
    "battery_bedtime_body",                # "... Charge before bed."
    "battery_stale_body",                  # "... Charge it before tonight."
    "l10n_connection_help_charge_it_and_put_it_on_31b04814",
    "l10n_intervals_screen_rest_b79e5f48", # work / rest intervals
    "l10n_today_screen_rest_hr_04005617",  # "Rest HR" = resting heart rate
}
SKIP_PREFIXES = ("l10n_app_changelog_",)   # release history says what shipped at the time

# Where a plain swap reads badly, say it properly.
OVERRIDES = {
    "l10n_weekly_digest_card_sleep_steadiness_rest_varied_fmt1_": "Sleep steadiness: your Sleep score varied ±%1$s pts night to night.",
}

STRING = re.compile(r'(<string\s+name="([^"]+)"[^>]*>)(.*?)(</string>)', re.S)


def main() -> None:
    src = SRC.read_text(encoding="utf-8")
    out = []
    for m in STRING.finditer(src):
        open_tag, name, body, close = m.groups()
        if name in SKIP or name.startswith(SKIP_PREFIXES):
            continue
        new = body
        for pat, rep in SWAPS:
            new = pat.sub(rep, new)
        if new == body:
            continue
        for key, text in OVERRIDES.items():
            if name.startswith(key):
                new = text
        out.append(f"    {open_tag}{new}{close}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- GENERATED by android/onyx/gen_score_names.py (FORK-ONLY): WHOOP's score names over NOOP's.\n"
        "     Do not edit by hand; re-run the script after an upstream merge. -->\n"
        '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="MissingTranslation,ExtraTranslation">\n'
        + "\n".join(out) + "\n</resources>\n",
        encoding="utf-8",
    )
    print(f"{len(out)} strings -> {OUT.relative_to(HERE.parent.parent)}")


if __name__ == "__main__":
    main()
